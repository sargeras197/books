const cards = document.querySelectorAll('.book-card');
const modal = document.getElementById('bookModal');
const closeBtn = document.getElementById('closeModal');
const modalImage = document.getElementById('modalImage');
const modalTitle = document.getElementById('modalTitle');
const modalShort = document.getElementById('modalShort');
const modalDetails = document.getElementById('modalDetails');

cards.forEach((card) => {
  card.addEventListener('click', () => {
    const index = Number(card.dataset.book);
    const book = books[index];
    if (!book) return;

    modalImage.src = book.image;
    modalImage.alt = book.title;
    modalTitle.textContent = book.title;
    modalShort.textContent = book.short;
    modalDetails.innerHTML = '';

    book.details.forEach(([label, value]) => {
      const row = document.createElement('div');
      row.className = 'detail-item';
      row.innerHTML = `<div class="detail-label">${label}</div><div class="detail-value">${value}</div>`;
      modalDetails.appendChild(row);
    });

    modal.classList.add('active');
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';
  });
});

function closeModal() {
  modal.classList.remove('active');
  modal.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
}

closeBtn.addEventListener('click', closeModal);
modal.addEventListener('click', (event) => {
  if (event.target === modal) {
    closeModal();
  }
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    closeModal();
  }
});
